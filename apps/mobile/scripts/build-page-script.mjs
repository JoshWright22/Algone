// Bundles src/page/entry.ts into one IIFE, kept as a string for the web view to inject.
// Runs before Metro: the output is gitignored, so postinstall, prestart, and CI all call it.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const app = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = (p) => resolve(app, "../../packages", p);

const result = await build({
  entryPoints: [resolve(app, "src/page/entry.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  charset: "ascii",
  legalComments: "none",
  write: false,
  alias: {
    "@algone/core": pkg("core/src/index.ts"),
    // A folder, so "@algone/engine/healthy" resolves too.
    "@algone/engine": pkg("engine/src"),
    "@algone/rules": pkg("rules/src/index.ts"),
  },
});

const code = result.outputFiles[0].text;
const out = resolve(app, "src/generated/pageScript.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/build-page-script.mjs. Do not edit.\nexport const PAGE_SCRIPT: string = ${JSON.stringify(code)};\n`,
);
console.log(`page script: ${code.length} characters`);
