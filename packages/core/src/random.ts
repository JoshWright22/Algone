import content from "./content/random.json";
import { makePuzzle, type Puzzle, seeded } from "./puzzles";

export interface RandomItem {
  kind: "quote" | "fact" | "poem" | "art" | "puzzle";
  text: string;
  source: string;
  file?: string;
  puzzle?: Puzzle;
}

const ITEMS = content as RandomItem[];

export const randomContentCount = () => ITEMS.length;

/** Picks an item. Puzzles are generated, everything else is bundled. */
export function pickRandom(seed: number): RandomItem {
  const r = seeded(seed);
  const i = Math.floor(r() * (ITEMS.length + 8));
  if (i >= ITEMS.length) {
    const puzzle = makePuzzle(seed);
    return { kind: "puzzle", text: puzzle.prompt, source: "Generated by Algone", puzzle };
  }
  return ITEMS[i]!;
}
